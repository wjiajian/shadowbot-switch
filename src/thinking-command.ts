import type { Prompt } from './adapter.js';
import { RequestError } from './errors.js';

export const thinkingCommands = {
  thinking: { template: '/thinking $ARGUMENTS', description: '空参数查询当前强度；填写 low、medium、high 等支持的档位切换' },
};

export function thinkingArgument(prompt: Prompt): string | undefined {
  if (prompt.noReply || !Array.isArray(prompt.parts)) return undefined;
  const parts = prompt.parts.filter(part => part.type !== 'text' || part.metadata?.xbotPartKind !== 'runtime_context');
  const first = parts.find(part => part.type === 'text');
  if (!first || first.type !== 'text') return undefined;
  const text = first.text.replace(/^\s*<!-- Generated by ShadowBot Switch for a Skill\. -->\s*/, '')
    .replaceAll('<!-- xbot-command-arguments:start -->', '').replaceAll('<!-- xbot-command-arguments:end -->', '').trim();
  const match = /^\/thinking(?:\s+([\s\S]*))?$/.exec(text);
  if (match && parts.length !== 1) throw new RequestError(400, '/thinking 不接受附件或额外内容，请只填写档位或留空查询。');
  return match ? (match[1] ?? '').trim() : undefined;
}
