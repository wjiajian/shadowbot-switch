import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadSkillsFromDir } from './skills.js';
import type { Skill } from './skills.js';
import { atomicWrite } from './installation.js';

const generated = '<!-- Generated by ShadowBot Switch for a Skill. -->';
const skillName = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const commandFile = /^skill-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/;

export function skillCommand(name: string) {
  return `请先调用 skill 工具读取 ${name}，再按该 Skill 的要求完成任务。\n\n$ARGUMENTS\n`;
}

export function syncSkillCommands(resources: string, directory?: string | Pick<Skill, 'name' | 'description'>[]) {
  const report = { added: 0, updated: 0, removed: 0, unchanged: 0, conflicts: [] as string[] };
  const commands = join(resources, 'Copilot', 'commands');
  const desired = new Map<string, string>();
  if (directory) {
    for (const { name, description } of typeof directory === 'string' ? loadSkillsFromDir({ dir: directory, source: 'custom' }).skills : directory) {
      const file = `skill-${name}.md`;
      if (!skillName.test(name) || desired.has(file)) continue;
      desired.set(file, [
        '---', `displayName: ${name}`, `description: ${JSON.stringify(description.replace(/\s+/g, ' ').trim())}`,
        'agent: shadowbot-copilot', 'subtask: false', '---', generated,
        skillCommand(name),
      ].join('\n'));
    }
  }

  const existing = existsSync(commands) ? readdirSync(commands, { withFileTypes: true }) : [];
  for (const entry of existing) {
    if (!entry.isFile() || !commandFile.test(entry.name)) continue;
    const path = join(commands, entry.name);
    const current = readFileSync(path, 'utf8');
    const next = desired.get(entry.name);
    if (current.replaceAll('\r\n', '\n').includes(`\n---\n${generated}\n`)) {
      if (!next) { unlinkSync(path); report.removed++; }
      else if (current !== next) { atomicWrite(path, next); report.updated++; }
      else report.unchanged++;
    } else if (next) {
      console.warn(`ShadowBot Switch left existing command ${entry.name} in place`);
      report.conflicts.push(entry.name);
    }
    desired.delete(entry.name);
  }

  if (desired.size) mkdirSync(commands, { recursive: true });
  for (const [name, content] of desired) {
    try { writeFileSync(join(commands, name), content, { flag: 'wx' }); report.added++; }
    catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
      console.warn(`ShadowBot Switch left existing command ${name} in place`);
      report.conflicts.push(name);
    }
  }
  return report;
}
