import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadSkillsFromDir } from './skills.js';
import type { Skill } from './skills.js';
import { atomicWrite } from './installation.js';
import { thinkingCommands } from './thinking-command.js';
import { parse } from 'yaml';
import { object } from './config.js';
import type { HostConfig } from './config.js';
import { RequestError } from './errors.js';

const generated = '<!-- Generated by ShadowBot Switch for a Skill. -->';
const skillName = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const commandFile = /^skill-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/;
// Include retired shortcuts so upgrades remove only our generated files.
const thinkingFile = /^thinking(?:-high|-medium)?\.md$/;

export function generatedCommand(content: string) {
  return content.replaceAll('\r\n', '\n').includes(`\n---\n${generated}\n`);
}

export function thinkingMenuCommand(resources: string): NonNullable<HostConfig['value']['command']>[string] {
  const file = join(resources, 'Copilot', 'commands', 'thinking.md');
  try {
    const text = readFileSync(file, 'utf8');
    if (generatedCommand(text)) return thinkingCommands.thinking;
    const header = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(text);
    const meta = header ? parse(header[1]) : {};
    return { template: header ? text.slice(header[0].length) : text,
      description: object(meta) && typeof meta.description === 'string' ? meta.description : undefined,
      agent: object(meta) && typeof meta.agent === 'string' ? meta.agent : undefined,
      model: object(meta) && typeof meta.model === 'string' ? meta.model : undefined };
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return thinkingCommands.thinking;
    throw new RequestError(400, '无法读取 thinking 命令文件，请检查文件类型、权限和格式。');
  }
}

export function skillCommand(name: string) {
  return `请先调用 skill 工具读取 ${name}，再按该 Skill 的要求完成任务。\n\n$ARGUMENTS\n`;
}

export function syncSkillCommands(resources: string, directory?: string | Pick<Skill, 'name' | 'description'>[], thinking = false) {
  const report = { added: 0, updated: 0, removed: 0, unchanged: 0, conflicts: [] as string[] };
  const commands = join(resources, 'Copilot', 'commands');
  const desired = new Map<string, string>();
  if (thinking) for (const [name, command] of Object.entries(thinkingCommands)) {
    desired.set(`${name}.md`, ['---', `displayName: ${name}`, `description: ${JSON.stringify(command.description)}`,
      'subtask: false', '---', generated,
      command.template.replace('$ARGUMENTS', '<!-- xbot-command-arguments:start -->$ARGUMENTS<!-- xbot-command-arguments:end -->'), ''].join('\n'));
  }
  if (directory) {
    for (const { name, description } of typeof directory === 'string' ? loadSkillsFromDir({ dir: directory, source: 'custom' }).skills : directory) {
      const file = `skill-${name}.md`;
      if (!skillName.test(name) || desired.has(file)) continue;
      desired.set(file, [
        '---', `displayName: ${name}`, `description: ${JSON.stringify(description.replace(/\s+/g, ' ').trim())}`,
        'agent: shadowbot-copilot', 'subtask: false', '---', generated,
        skillCommand(name),
      ].join('\n'));
    }
  }

  const existing = existsSync(commands) ? readdirSync(commands, { withFileTypes: true }) : [];
  for (const entry of existing) {
    if (!entry.isFile() || (!commandFile.test(entry.name) && !thinkingFile.test(entry.name))) continue;
    const path = join(commands, entry.name);
    const current = readFileSync(path, 'utf8');
    const next = desired.get(entry.name);
    if (generatedCommand(current)) {
      if (!next) { unlinkSync(path); report.removed++; }
      else if (current !== next) { atomicWrite(path, next); report.updated++; }
      else report.unchanged++;
    } else if (next) {
      console.warn(`菜单命令 ${entry.name} 已有同名文件，保留原文件，未覆盖。`);
      report.conflicts.push(entry.name);
    }
    desired.delete(entry.name);
  }

  if (desired.size) mkdirSync(commands, { recursive: true });
  for (const [name, content] of desired) {
    try { writeFileSync(join(commands, name), content, { flag: 'wx' }); report.added++; }
    catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
      console.warn(`菜单命令 ${name} 已有同名文件，保留原文件，未覆盖。`);
      report.conflicts.push(name);
    }
  }
  return report;
}
