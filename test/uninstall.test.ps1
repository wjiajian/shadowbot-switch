# 依赖 PATH 中的 node 和已构建的 dist/service（npm run build）。
$ErrorActionPreference = 'Stop'
$repository = Split-Path $PSScriptRoot
. (Join-Path $repository 'scripts/maintenance.ps1')
$project = (New-Item -ItemType Directory -Path (Join-Path ([IO.Path]::GetTempPath()) "shadowbot-uninstall-$([guid]::NewGuid())")).FullName
$state = Join-Path $project '.shadowbot-switch'
$original = Join-Path $state 'original/opencode.exe'
$agent = Join-Path $project 'shadowbot-6.3.39/opencode.exe'
$locator = "$agent.shadowbot-pi.json"

function Get-SwitchProcesses { }
function Invoke-RuntimeControl($StateDirectory, $Install, [string[]]$Arguments) {
    if ($StateDirectory -ne $state -or ($Arguments -join ' ') -ne 'backend original') { throw 'Wrong backend switch.' }
    if ($failSwitch) { throw 'fixture control failure' }
    $sync = [uri]::new((Join-Path $repository 'dist/service/skill-commands.js')).AbsoluteUri
    & node --input-type=module -e 'const {syncSkillCommands} = await import(process.argv[1]); syncSkillCommands(process.argv[2]);' $sync $Install.resources
    if ($LASTEXITCODE -ne 0) { throw 'Skill cleanup failed.' }
    $script:switched = $true
}
function Assert-UninstallError([scriptblock]$Action, $Pattern) {
    try { & $Action } catch {
        if ($_.Exception.Message -notmatch $Pattern) { throw }
        return
    }
    throw "Expected failure: $Pattern"
}
try {
    foreach ($path in (Split-Path $original), (Split-Path $agent), (Join-Path $project 'harnesses/original/node_modules')) {
        New-Item -ItemType Directory -Force -Path $path | Out-Null
    }
    Copy-Item -LiteralPath (Join-Path $repository 'harnesses/original/harness.json') -Destination (Join-Path $project 'harnesses/original')
    foreach ($path in '.tools', 'dist', 'node_modules', '.shadowbot-switch/backends', '.shadowbot-switch/ui-staging', '.shadowbot-switch/skills', '.shadowbot-switch/agent', '.shadowbot-switch/harnesses/pi/agent', '.shadowbot-switch/harnesses/pi/releases', '.shadowbot-switch/harnesses/pi/dependencies') {
        New-Item -ItemType Directory -Path (Join-Path $project $path) | Out-Null
    }
    Set-Content -LiteralPath $original -Value 'fixture bundled'
    Set-Content -LiteralPath $agent -Value 'fixture launcher'

    $install = @{ agentPath = $agent }
    $local = [Environment]::GetFolderPath('LocalApplicationData')
    $install.database = Join-Path $local 'ShadowBot/opencode/runtime/shared/xdg_data/opencode/opencode.db'
    $install.users = Join-Path $local 'ShadowBot/users'
    $install.resources = Join-Path (Split-Path $agent) 'Resources'
    $commands = New-Item -ItemType Directory -Force -Path (Join-Path $install.resources 'Copilot/commands')
    $generated = Join-Path $commands.FullName 'skill-fixture.md'
    Set-Content -LiteralPath $generated -Value "---`ndisplayName: fixture`n---`n<!-- Generated by ShadowBot Switch for a Skill. -->`n"
    Set-Content -LiteralPath (Join-Path $commands.FullName 'skill-user.md') -Value 'user command'
    Write-AtomicJson (Join-Path $state 'install.json') $install
    Write-AtomicJson (Join-Path $state 'backend.json') @{mode = 'pi'}
    Write-AtomicJson $locator @{home = $state}
    try { Uninstall-Project $project -ShadowBotDirectory $state; throw 'Accepted wrong directory.' }
    catch { if ($_.Exception.Message -notmatch '与安装记录不一致') { throw } }
    Write-AtomicJson $locator @{home = 'foreign-project'}
    try { Uninstall-Project $project; throw 'Accepted foreign launcher.' }
    catch { if ($_.Exception.Message -notmatch '不属于此项目') { throw } }
    Write-AtomicJson $locator @{home = $state}
    $failSwitch = $true
    try { Uninstall-Project $project; throw 'Ignored control failure.' } catch { if ($_.Exception.Message -ne 'fixture control failure') { throw } }
    $install.runtimeRelease = 'a' * 64
    $runtime = Get-InstallationRuntime $state $install
    New-Item -ItemType Directory -Path $runtime -Force | Out-Null
    Copy-Item -LiteralPath $agent -Destination (Join-Path $runtime 'launcher.exe')
    Copy-Item -LiteralPath $original -Destination $agent -Force
    Write-AtomicJson (Join-Path $state 'install.json') $install
    $failSwitch = $false
    $result = Uninstall-Project $project
    if (!$switched -or $result.restored -ne $agent -or (Get-Content -LiteralPath $agent) -ne 'fixture bundled') { throw 'Bundled backend or executable was not restored.' }
    if (!(Test-Path -LiteralPath (Join-Path $commands.FullName 'skill-user.md'))) { throw 'User command was removed.' }
    foreach ($path in (Join-Path $state 'ui-staging'), (Join-Path $state 'harnesses/pi/releases'), (Join-Path $state 'harnesses/pi/dependencies'), $generated, $locator, $original, (Join-Path $state 'install.json'), (Join-Path $project '.tools'), (Join-Path $project 'dist'), (Join-Path $project 'node_modules'), (Join-Path $project 'harnesses/original/node_modules')) {
        if (Test-Path -LiteralPath $path) { throw "Left behind: $path" }
    }
    foreach ($name in 'backends', 'skills', 'agent', 'harnesses/pi/agent') {
        if (!(Test-Path -LiteralPath (Join-Path $state $name))) { throw "Lost history: $name" }
    }
    New-Item -Force -ItemType Directory -Path (Split-Path $original) | Out-Null
    Copy-Item -LiteralPath $agent -Destination $original
    Write-AtomicJson (Join-Path $state 'install.json') $install
    Write-AtomicJson $locator @{home = 'foreign-project'}
    Set-Content -LiteralPath $agent 'foreign launcher'
    Uninstall-Project $project -PurgeData -Yes | Out-Null
    if ((Get-Content -LiteralPath $agent) -ne 'foreign launcher') { throw 'Foreign launcher changed.' }
    if ((Test-Path -LiteralPath $state) -or !(Test-Path -LiteralPath $locator)) { throw 'Purge or locator ownership check failed.' }
    New-Item -ItemType Directory -Path (Join-Path $project '.tools') | Out-Null
    $result = Uninstall-Project $project
    if ($result.removed.Count -ne 1 -or (Uninstall-Project $project).removed.Count) { throw 'Cleanup without installation was not idempotent.' }
    New-Item -ItemType Directory -Force -Path (Split-Path $original), $runtime | Out-Null
    Set-Content -LiteralPath $original 'fixture bundled'
    Set-Content -LiteralPath (Join-Path $runtime 'launcher.exe') 'fixture launcher'
    Remove-Item -LiteralPath $locator, $agent
    $pending = Join-Path $state 'activation.pending.json'
    Write-AtomicJson $pending @{ release = $install }
    Assert-UninstallError { Uninstall-Project $project } '安装尚未完成'
    Copy-Item -LiteralPath $original -Destination $agent
    $result = Uninstall-Project $project
    if ($result.restored -ne $agent -or (Test-Path -LiteralPath $pending)) { throw 'Activation recovery failed.' }

    New-Item -ItemType Directory -Force -Path (Split-Path $original) | Out-Null
    Copy-Item -LiteralPath $agent -Destination $original
    Write-AtomicJson (Join-Path $state 'install.json') $install
    Write-AtomicJson $locator @{ home = (Join-Path $local 'ShadowBotPi') }
    Assert-UninstallError { Uninstall-Project $project } '不属于此项目'
    Remove-Item -LiteralPath $locator
    New-Item -ItemType Directory -Force -Path (Split-Path $original) | Out-Null
    Copy-Item -LiteralPath $agent -Destination $original
    Remove-Item -LiteralPath $agent
    Write-AtomicJson (Join-Path $state 'install.json') $install
    Assert-UninstallError { Uninstall-Project $project -ShadowBotDirectory (Join-Path $project 'missing') } '指定的影刀目录不存在'
    $result = Uninstall-Project $project -ShadowBotDirectory "$project$([IO.Path]::DirectorySeparatorChar)"
    if ($result.restored -or (Test-Path -LiteralPath (Join-Path $state 'install.json'))) { throw 'Missing host or trailing separator blocked local cleanup.' }
    Uninstall-Project $project | Out-Null
    if (!(Test-Path -LiteralPath $original)) { throw 'Backup disappeared without a host.' }
    # Missing host with managed mode and --purge-data preserves the backup, while other state is purged.
    Write-AtomicJson (Join-Path $state 'install.json') $install
    Write-AtomicJson (Join-Path $state 'backend.json') @{ mode = 'pi' }
    Uninstall-Project $project -PurgeData -Yes | Out-Null
    if (!(Test-Path -LiteralPath $original) -or (Test-Path -LiteralPath (Join-Path $state 'install.json'))) { throw 'Missing host purge mishandled backup.' }
    Remove-Item -LiteralPath (Join-Path $state 'install.json') -ErrorAction SilentlyContinue
    Assert-UninstallError { Uninstall-Project $project -PurgeData -Yes } '请用 --shadowbot-dir'
    Set-Content -LiteralPath (Join-Path $project 'ShadowBot.exe') 'fixture'
    Set-Content -LiteralPath $agent 'managed'
    Write-AtomicJson $locator @{ home = $state }
    Assert-UninstallError { Uninstall-Project $project -PurgeData -Yes -ShadowBotDirectory $project } '已保留原版备份'
    Remove-Item -LiteralPath $locator
    Copy-Item -LiteralPath $original -Destination $agent -Force
    Copy-Item -LiteralPath (Join-Path $repository 'scripts') -Destination $project -Recurse
    $cli = Join-Path $project 'switch.ps1'
    Copy-Item -LiteralPath (Join-Path $repository 'switch.ps1') -Destination $cli
    $pwsh = (Get-Process -Id $PID).Path
    $refused = '' | & $pwsh -NoProfile -File $cli uninstall --purge-data --json | Out-String
    if ($LASTEXITCODE -ne 1 -or ($refused | ConvertFrom-Json).error -notmatch '需要 --yes') { throw 'Redirected purge did not require confirmation.' }
    Uninstall-Project $project -PurgeData -Yes -ShadowBotDirectory $project | Out-Null
    if (Test-Path -LiteralPath $state) { throw 'Verified purge failed.' }

    New-Item -ItemType Directory -Force -Path (Split-Path $original) | Out-Null
    Copy-Item -LiteralPath $agent -Destination $original
    Set-Content -LiteralPath $agent 'foreign launcher'
    Write-AtomicJson $locator @{ home = $state }
    Assert-UninstallError { Uninstall-Project $project -PurgeData -Yes -ShadowBotDirectory $project } '已保留原版备份'
    $missingForeign = Join-Path $project 'missing-other-state'
    Write-AtomicJson $locator @{ home = $missingForeign }
    Assert-UninstallError { Uninstall-Project $project -PurgeData -Yes -ShadowBotDirectory $project } '已保留原版备份'
    $otherState = Join-Path $project 'other-state'
    New-Item -ItemType Directory -Force -Path (Join-Path $otherState 'original') | Out-Null
    Copy-Item -LiteralPath $original -Destination (Join-Path $otherState 'original/opencode.exe')
    Write-AtomicJson $locator @{ home = $otherState }
    Uninstall-Project $project -PurgeData -Yes -ShadowBotDirectory $project | Out-Null
    if ((Test-Path -LiteralPath $original) -or !(Test-Path -LiteralPath $locator)) { throw 'Verified foreign-owner purge failed.' }

    # Missing original backup during host restore throws a Chinese error.
    New-Item -ItemType Directory -Force -Path $state | Out-Null
    Write-AtomicJson (Join-Path $state 'install.json') $install
    Write-AtomicJson $locator @{ home = $state }
    Assert-UninstallError { Uninstall-Project $project } '原程序备份缺失'
    Remove-Item -LiteralPath (Join-Path $state 'install.json'), $locator -Force

    # Managed backend running with ShadowBot and project node.exe waits under --wait instead of failing immediately.
    & {
        New-Item -ItemType Directory -Force -Path (Split-Path $original), $runtime, (Join-Path $project '.tools') | Out-Null
        Set-Content -LiteralPath $original 'fixture bundled'
        Copy-Item -LiteralPath $original -Destination (Join-Path $runtime 'launcher.exe') -Force
        Set-Content -LiteralPath $agent 'fixture launcher'
        Write-AtomicJson (Join-Path $state 'install.json') $install
        Write-AtomicJson (Join-Path $state 'backend.json') @{ mode = 'pi' }
        Write-AtomicJson $locator @{ home = $state }
        $script:hostChecks = 0
        $script:nodeChecks = 0
        function Get-SwitchProcesses {
            $script:hostChecks++
            if ($script:hostChecks -lt 3) { [pscustomobject]@{ Id = 999; ProcessName = 'ShadowBot'; Path = 'ShadowBot.exe' } }
        }
        function Get-Process {
            if ($script:hostChecks -lt 3) { return [pscustomobject]@{ Id = -1; Path = (Join-Path $runtime 'node.exe') } }
            $script:nodeChecks++
            if ($script:nodeChecks -lt 2) { [pscustomobject]@{ Id = -1; Path = (Join-Path $runtime 'node.exe') } }
        }
        $waitResult = Uninstall-Project $project -Wait
        if ($script:hostChecks -lt 3 -or $script:nodeChecks -lt 2 -or $waitResult.restored -ne $agent) { throw 'Wait flow did not wait for ShadowBot and project node.' }
        Remove-Item -LiteralPath $state -Recurse -Force
    }

    $tools = Join-Path $project '.tools'
    $dist = Join-Path $project 'dist'
    $linkType = if ($IsWindows) { 'Junction' } else { 'SymbolicLink' }
    New-Item -ItemType $linkType -Path $tools -Target (Split-Path $agent) | Out-Null
    New-Item -ItemType Directory -Path $dist | Out-Null
    $result = Uninstall-Project $project
    if ($result.failed.Count -ne 1 -or $result.failed[0].path -ne $tools -or $result.failed[0].reason -notmatch '链接' -or
        (Test-Path -LiteralPath $dist) -or !(Test-Path -LiteralPath $agent)) { throw 'Linked target or failure collection mishandled.' }
    $stderr = Join-Path $project 'stderr.log'
    $summary = & $pwsh -NoProfile -File $cli uninstall --json 2>$stderr | Out-String
    if ($LASTEXITCODE -ne 1 -or ($summary | ConvertFrom-Json).failed[0].path -ne $tools -or
        !(Get-Content -LiteralPath $stderr -Raw).Contains($tools)) { throw 'CLI lost cleanup failure details.' }
    Remove-Item -LiteralPath $tools
    New-Item -ItemType Directory -Path $tools, $dist | Out-Null
    & {
        function Get-Process { [pscustomobject]@{ Id = -1; Path = (Join-Path $tools 'node.exe') } }
        Assert-UninstallError { Uninstall-Project $project } '请先关闭项目中的进程'
        if (!(Test-Path -LiteralPath $dist)) { throw 'Partial cleanup before process check.' }
    }
    & {
        function Remove-Item($LiteralPath, [switch]$Force, [switch]$Recurse, $ErrorAction) {
            if ($LiteralPath -eq $tools) { throw 'fixture file in use' }
            Microsoft.PowerShell.Management\Remove-Item @PSBoundParameters
        }
        $result = Uninstall-Project $project
        if ($result.failed[0].reason -ne 'fixture file in use' -or $result.failed[0].path -ne $tools -or $dist -notin $result.removed) { throw 'Removal failure interrupted cleanup.' }
    }
    'Uninstall tests passed.'
} finally { Remove-Item -LiteralPath $project -Recurse -Force }
