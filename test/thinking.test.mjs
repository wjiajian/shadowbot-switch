import assert from 'node:assert/strict';
import test from 'node:test';
import { getSupportedThinkingLevels } from '@earendil-works/pi-ai';
import { HostConfig } from '../dist/service/adapters/pi/config.js';
import { thinkingArgument } from '../dist/service/thinking-command.js';
import { syncSkillCommands } from '../dist/service/skill-commands.js';
import { mkdtempSync, mkdirSync, writeFileSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

test('menu upgrade removes generated shortcuts and preserves user files', () => {
  const root = mkdtempSync(join(tmpdir(), 'thinking-menu-'));
  const commands = join(root, 'Copilot', 'commands');
  mkdirSync(commands, { recursive: true });
  try {
    const generated = '---\ndisplayName: shortcut\n---\n<!-- Generated by ShadowBot Switch for a Skill. -->\n/thinking high';
    for (const name of ['thinking-high', 'thinking-medium']) writeFileSync(join(commands, `${name}.md`), generated);
    const result = syncSkillCommands(root, undefined, true);
    assert.equal(result.removed, 2);
    assert.deepEqual(readdirSync(commands), ['thinking.md']);
    assert.match(readFileSync(join(commands, 'thinking.md'), 'utf8'), /\/thinking <!-- xbot-command-arguments:start -->\$ARGUMENTS<!-- xbot-command-arguments:end -->/);
    writeFileSync(join(commands, 'thinking-high.md'), 'User command');
    syncSkillCommands(root, undefined, true);
    assert.equal(readFileSync(join(commands, 'thinking-high.md'), 'utf8'), 'User command');
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test('native thinking template and runtime context remain a local command', () => {
  const text = '<!-- Generated by ShadowBot Switch for a Skill. -->\n/thinking <!-- xbot-command-arguments:start -->high<!-- xbot-command-arguments:end -->';
  const parts = [{ type: 'text', text }, { type: 'text', text: 'host context', metadata: { xbotPartKind: 'runtime_context' } }];
  assert.equal(thinkingArgument({ parts }), 'high');
  assert.equal(thinkingArgument({ parts, noReply: true }), undefined);
  assert.equal(thinkingArgument({ parts: [{ type: 'text', text: 'Explain /thinking high' }] }), undefined);
});

test('custom endpoint preserves catalog-specific thinking restrictions', async () => {
  const config = new HostConfig();
  config.value = { model: 'openai/gpt-6-astra', provider: { openai: {
    options: { baseURL: 'http://localhost:1234' }, models: { 'gpt-6-astra': {} },
  } } };
  const { resolved } = await config.model();
  assert.deepEqual(getSupportedThinkingLevels(resolved), ['low', 'medium', 'high', 'xhigh', 'max']);
  assert.equal(resolved.thinkingLevelMap.off, null);
  config.value.provider.openai.npm = '@ai-sdk/openai-compatible';
  const compatible = (await config.model()).resolved;
  assert.equal(compatible.api, 'openai-completions');
  assert.deepEqual(getSupportedThinkingLevels(compatible), getSupportedThinkingLevels(resolved));
});
